import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {open} from '../lib/db.mjs';
import {migrateAgent,enqueue,claimNext} from '../lib/agentdb.mjs';
import {migrateSales,revenueSummary} from '../lib/salesdb.mjs';
import {migrateOutbound,previewOutbound,dispatchOutbound} from '../lib/outbound.mjs';
import {migrateMailRecords,saveMailRecord} from '../lib/mail-records.mjs';
import {ownerSalesPause,pauseOwnerSales,resumeOwnerSales,OWNER_SALES_PAUSE_REASON} from '../lib/owner-sales-pause.mjs';
import {draftDecision} from '../agent/draft-policy.mjs';
import {prepareInput,applyOutput} from '../agent/runtime.mjs';
import {performJob} from '../agent/worker.mjs';
import {planConductor} from '../agent/conductor.mjs';
import {bulkGate} from '../lib/gates.mjs';
import {sendGate} from '../lib/sendgate.mjs';
import {jarelGate} from '../lib/jarelgate.mjs';
import {reconcileSalesReplies,suppressionReason} from '../lib/sales-safety.mjs';

const dir=mkdtempSync(join(tmpdir(),'leisson-owner-pause-')),path=join(dir,'fixture.sqlite');
let db=open({dbPath:path});
const now=new Date(),accounts=[{id:'gert',user:'gert@leisson.eu'}];
const options={now,accounts,composeText:x=>x,composeHtml:x=>'<p>'+x+'</p>'};
try {
 // A read-only guard does not create a schema or load mailbox credentials.
 assert.equal(ownerSalesPause(db,{address:'friend@example.test'}),null);
 assert.equal(db.prepare("SELECT 1 FROM sqlite_master WHERE name='owner_sales_pauses'").get(),undefined);
 migrateAgent(db);migrateSales(db);migrateOutbound(db);migrateMailRecords(db);
 const add=db.prepare("INSERT INTO companies(id,name,email,status,subject,body,listid,price,sales_state,need_evidence) VALUES(?,?,?,'ootel','A scoped offer','A small fixed job','parnu',590,'qualified','A confirmed request')");
 add.run('friend','Synthetic friend','friend@example.test');add.run('buyer','Synthetic buyer','buyer@example.test');
 const r=saveMailRecord(db,{account:'gert',mailbox:'INBOX',uidvalidity:'100',uid:1,msgid:'friend-1@example.test',ts:now.toISOString(),direction:'in',addr:'friend@example.test',subject:'Please quote',body_text:'Soovin pakkumist kodulehele.',company_id:'friend'});
 db.prepare("UPDATE messages SET classified=1,category='paring',reply_intent='positive'").run();
 const message=db.prepare('SELECT * FROM messages WHERE uid=1').get(),messageId='source:'+r.source_id;
 const envelope={kind:'sales',companyId:'friend',accountId:'gert',to:'friend@example.test',subject:'A scoped offer',body:'A small fixed job'};
 const preview=previewOutbound(db,envelope,options);
 assert.equal(draftDecision(db,message,{now}).allowed,true);
 const jobId=enqueue(db,'draft',{message_id:messageId}),job=claimNext(db),input=prepareInput(db,job,{now});
 const first=pauseOwnerSales(db,{address:'  FRIEND@EXAMPLE.TEST  ',reason:'Owner excludes personal relationship from current sales',now});
 assert.equal(first.company_id,'friend');assert.equal(first.kind,'owner_request');assert.equal(first.legalOptOut,false);
 assert.equal(pauseOwnerSales(db,{address:'friend@example.test',now:new Date(+now+1000)}).paused_at,first.paused_at,'idempotent application preserves pause start');
 assert.equal(db.prepare('SELECT COUNT(*) n FROM suppressions').get().n,0);
 assert.equal(db.prepare('SELECT reply_intent FROM messages WHERE uid=1').get().reply_intent,'positive');
 assert.equal(draftDecision(db,message,{now}).reason,OWNER_SALES_PAUSE_REASON);
 assert.equal(bulkGate(db,'mustand',[messageId]).passN,0);
 assert.equal(planConductor(db,{now}).jobs.filter(j=>j.type==='draft').length,0);
 assert.throws(()=>applyOutput(db,job,input,{message_id:messageId,subject:'Re: Please quote',body:'Here is the quote.',lang:'et',confidence:1,blocker:null},{now}),/müügipaus/);
 let modelCalls=0;
 const run=await performJob(db,job,{runner:async()=>{modelCalls++;throw Error('model must not run');}});
 assert.equal(modelCalls,0);assert.match(run.error,/müügipaus/);
 assert.equal(db.prepare('SELECT status FROM agent_jobs WHERE id=?').get(jobId).status,'needs_human');
 assert.throws(()=>previewOutbound(db,envelope,options),/müügipaus/);
 assert.throws(()=>previewOutbound(db,{...envelope,to:'colleague@example.test'},options),/müügipaus/,'company association prevents recipient substitution');
 assert.throws(()=>previewOutbound(db,{kind:'reply',account:'gert',uid:1,to:message.addr,subject:'Re: Please quote',body:'A reply'},options),/müügipaus/);
 let smtpCalls=0;
 await assert.rejects(dispatchOutbound(db,preview.approvalId,envelope,async()=>{smtpCalls++;throw Error('SMTP must not run');},{now,accounts}),/müügipaus/);
 assert.equal(smtpCalls,0);assert.equal(db.prepare('SELECT COUNT(*) n FROM outbound_messages').get().n,0);
 assert.equal(sendGate(db,{now}).miks[OWNER_SALES_PAUSE_REASON],1);
 db.prepare("INSERT INTO activity(company_id,ts,kind,note) VALUES('friend',?,'sent','Synthetic historic mail')").run(new Date(+now-14*86400000).toISOString());
 assert.equal(jarelGate(db,{now}).miks[OWNER_SALES_PAUSE_REASON],1);
 db.prepare("INSERT INTO drafts(account,uid,company_id,subject,body,status,created) VALUES('gert',1,'friend','Old draft','Body','ootab_kinnitust',?)").run(now.toISOString());
 reconcileSalesReplies(db,{apply:true,now});
 assert.equal(db.prepare('SELECT status FROM drafts WHERE uid=1').get().status,'tagasi_lukatud');
 assert.equal(db.prepare('SELECT reply_intent FROM messages WHERE uid=1').get().reply_intent,'positive');
 assert.equal(suppressionReason(db,message.addr),null);
 assert.equal(ownerSalesPause(db,{address:message.addr}).kind,'owner_request','positive replies cannot release owner pause');
 assert.equal(revenueSummary(db,{now}).qualified,1);assert.equal(revenueSummary(db,{now}).awaitingReply,0);
 assert.equal(ownerSalesPause(db,{address:'buyer@example.test'}),null,'does not pause a whole shared email domain');
 assert.ok(previewOutbound(db,{...envelope,companyId:'buyer',to:'buyer@example.test'},options).approvalId);
 db.close();db=open({dbPath:path});
 assert.equal(ownerSalesPause(db,{address:message.addr}).kind,'owner_request','pause survives process restart');
 db.prepare("INSERT INTO suppressions(addr,reason,ts,by) VALUES(?,'Separate recipient opt-out',?,'inbound')").run(message.addr,now.toISOString());
 assert.equal(resumeOwnerSales(db,{address:message.addr,now}).resumed,true);
 assert.equal(ownerSalesPause(db,{address:message.addr}),null);
 assert.equal(suppressionReason(db,message.addr),'Separate recipient opt-out','resuming owner pause never erases recipient opt-out');
 assert.throws(()=>previewOutbound(db,envelope,options),/opt-out/);
 console.log('PASS owner sales pause: persistent and idempotent, distinct from opt-out, draft/queued-run/commit blocked, old approval and all send gates blocked, unrelated contact preserved, explicit resume leaves legal opt-out intact.');
} finally {
 db.close();rmSync(dir,{recursive:true,force:true,maxRetries:5,retryDelay:100});
}
